"""Build a Z-machine hosted 6502 compatibility port from verified disk extraction.
No original input is modified. Uses Inform 6 without its adventure library.
"""
from pathlib import Path
import os,sys,subprocess,argparse,json
HERE=Path(__file__).resolve().parent;ROOT=HERE.parent
if HERE.name!='work' or HERE.parent.parent.name!='build':
    raise SystemExit('Run scripts/build.py; generated artifacts must stay under private build/<variant>/work/.')
from mos6502 import OPS
p=argparse.ArgumentParser();p.add_argument('--unit',type=Path);p.add_argument('--out',type=Path,default=HERE/'out');p.add_argument('--trace',action='store_true');p.add_argument('--seed',type=int,default=-1);p.add_argument('--version',type=int,default=5);a=p.parse_args();a.out.mkdir(parents=True,exist_ok=True)
import hashlib
m=(HERE/'memory.bin').read_bytes();
assert len(m)==65536
assert hashlib.sha256(m).hexdigest()=="ba24aab557e5f57f7bc8f687e6b11cf6cd4d82181aa11fd495f47b61dc59369c", "Unexpected source memory image"
startup=json.loads((HERE/'startup.json').read_text())
prepared=(HERE/'startup.bin').read_bytes()
ram=prepared[:0xd000]+prepared[0xe000:]
src=['! Generated by build.py from original extracted bytes.','Release 4;','Serial "261108";']
if a.trace:src+=['Constant PORT_TRACE;']
src+=['Constant FIXED_SEED = %d;'%a.seed]
src += ['Global '+x+';' for x in ['ra','rx','ry','rs','pc','fc','fz','fn','fv','fd','fi','op','addr','val','old','tmp','carry','seed','turns','lastpc']]
src+=['Array inputbuf -> 254 0 '+ '0 '*254+';']
src+=['Array ram ->\n'+'\n'.join(' '.join(str(x) for x in ram[i:i+32]) for i in range(0,len(ram),32))+';']
src+=['Array dispatch --> '+' '.join('I%02X'%i if i in OPS else 'Bad' for i in range(256))+';']
def rendered(raw):
 return ''.join('\n' if c==13 else chr(c-128) if 193<=c<=218 else chr(c+32) if 65<=c<=90 else chr(c) if 32<=c<=126 else '' for c in raw)
def quoted(text):return '"'+text.replace('@','@@64').replace('"','~').replace('\n','^')+'"'
unique=list(dict.fromkeys(startup['outputs']))
for i,value in enumerate(unique):
 src+=['[ StartupOutput%d;'%i,'#Ifdef PORT_TRACE;','print '+quoted(value.upper())+';','#Ifnot;','print '+quoted(rendered(bytes.fromhex(value)))+';','#Endif;','];']
# Generated executable setters live above readable memory, preserving room for
# the emulated 60 KiB RAM. No seed tables or game state are stored in source.
for seed,row in enumerate(startup['values']):
 src+=['[ StartupSeed%d;'%seed]
 for addr,value in zip(startup['addresses'],row):src+=['Write(%d,%d);'%(addr,value)]
 for name,value in zip(['ra','rx','ry','rs','fc','fz','fn','fv','fd'],startup['registers'][seed]):src+=['%s=%d;'%(name,value)]
 src+=['StartupOutput%d(); ];'%unique.index(startup['outputs'][seed])]
src+=['Array startup_dispatch --> '+' '.join('StartupSeed%d'%seed for seed in range(256))+';']
src+=['[ BootCase; seed=FIXED_SEED;if(seed<0)seed=random(256)-1;indirect(startup_dispatch-->seed);pc=$cab; ];']
src += [(HERE/'runtime.inf').read_text()]
for byte,(op,mode) in OPS.items():
 s=['[ I%02X;'%byte]
 if mode in ['n','r']:s+=['val=Fetch();']
 elif mode in ['z','zx','zy','ix','iy']:
  s+=['addr=Fetch();']
  if mode=='zx':s+=['addr=(addr+rx)&255;']
  if mode=='zy':s+=['addr=(addr+ry)&255;']
  if mode=='ix':s+=['addr=(addr+rx)&255; addr=Read(addr)+256*Read((addr+1)&255);']
  if mode=='iy':s+=['addr=Read(addr)+256*Read((addr+1)&255)+ry;']
 elif mode in ['w','wx','wy','ind']:
  s+=['addr=Word();']
  if mode=='wx':s+=['addr=addr+rx;']
  if mode=='wy':s+=['addr=addr+ry;']
 if mode not in ['i','a','n','r'] and op not in ['STA','STX','STY','JMP','JSR']:s+=['val=Read(addr);']
 if op in ['LDA','LDX','LDY']:s+=['r%s=NZ(val);'%op[-1].lower()]
 elif op in ['STA','STX','STY']:s+=['Write(addr,r%s);'%op[-1].lower()]
 elif op in ['CMP','CPX','CPY']:s+=['Compare(r%s,val);'%('a' if op=='CMP' else op[-1].lower())]
 elif op=='BIT':s+=['fn=(val&128)/128;fv=(val&64)/64;fz=((ra&val)==0);']
 elif op in ['AND','ORA']:s+=['ra=NZ(ra%sval);'%{'AND':'&','ORA':'|'}[op]]
 elif op=='EOR':s+=['ra=NZ(Xor(ra,val));']
 elif op in ['ADC','SBC']:s+=['Arithmetic(val,%d);'%(op=='SBC')]
 elif op in ['ASL','LSR','ROL','ROR']:
  s+=['old=%s;carry=fc;'%('ra' if mode=='a' else 'val')]
  if op in ['ASL','ROL']:s+=['fc=(old&128)/128;val=NZ(old*2%s);'%('+carry' if op=='ROL' else '')]
  else:s+=['fc=old&1;val=NZ(old/2%s);'%('+carry*128' if op=='ROR' else '')]
  s+=['ra=val;' if mode=='a' else 'Write(addr,val);']
 elif op in ['INC','DEC']:s+=['Write(addr,NZ(val%s1));'%('+' if op=='INC' else '-')]
 elif op in ['INX','INY','DEX','DEY']:
  r='r'+op[-1].lower();s+=['%s=NZ(%s%s1);'%(r,r,'+' if op.startswith('IN') else '-')]
 elif op in ['TAX','TAY','TXA','TYA','TSX','TXS']:
  s+=['r%s=%s;'%(op[2].lower(),'r'+op[1].lower() if op[2]=='S' else 'NZ(r%s)'%op[1].lower())]
 elif op=='PHA':s+=['Push(ra);']
 elif op=='PLA':s+=['ra=NZ(Pop());']
 elif op=='PHP':s+=['Push(fc+fz*2+fi*4+fd*8+48+fv*64+fn*128);']
 elif op=='PLP':s+=['Flags(Pop());']
 elif op=='RTI':s+=['Flags(Pop()); pc=Pop()+256*Pop();']
 elif op=='JSR':s+=['tmp=pc-1; @log_shift tmp (-8) old; Push(old); Push(tmp); pc=addr;']
 elif op=='RTS':s+=['Return6502();']
 elif op=='JMP':s+=['pc=addr;' if mode=='w' else 'pc=Read(addr)+256*Read((addr&$ff00)|((addr+1)&255));']
 elif mode=='r':
  cond={'BCC':'fc==0','BCS':'fc','BEQ':'fz','BNE':'fz==0','BMI':'fn','BPL':'fn==0','BVC':'fv==0','BVS':'fv'}[op]
  s+=['if (%s) { if (val>127) val=val-256; pc=pc+val; }'%cond]
 elif op in ['CLC','SEC','CLD','SED','CLI','SEI','CLV']:
  s+=[{'CLC':'fc=0;','SEC':'fc=1;','CLD':'fd=0;','SED':'fd=1;','CLI':'fi=0;','SEI':'fi=1;','CLV':'fv=0;'}[op]]
 elif op=='BRK':s+=['Bad();']
 elif op!='NOP':raise ValueError(op)
 src+=s+['];']
name='robots'+('-trace' if a.trace else '')
source='\n'.join(src)+'\n'
if a.unit:source=source.replace('[ Main;','[ GameMain;')+a.unit.read_text()
(a.out/f'{name}.inf').write_text(source)
subprocess.run([os.environ.get('INFORM6',str(ROOT/'tooling/inform6')),'-v%d'%a.version,'-~S',str(a.out/f'{name}.inf'),str(a.out/f'{name}.z{a.version}')],check=True)
